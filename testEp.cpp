static int checkClose(const string& label, double a, double b, double tol = 1e-10)
{
  const double diff = fabs(a - b);
  if(diff <= tol)
  {
    cout << label << " passes." << endl;
    return 0;
  }
  cout << "FAILURE: " << label << ": |a-b|=" << diff
       << " (a=" << a << ", b=" << b << ")" << endl;
  return 1;
}

static int testMomentsMatchGPyFormula()
{
  const double tau = 2.0;
  const double v = 1.0;
  const double sign = 1.0;
  const double den = sqrt(tau * tau + tau);
  const double z = sign * v / den;
  const double phiOverPhi = ndlutil::gradLnCumGaussian(z);
  const double Zref = exp(ndlutil::lnCumGaussian(z));
  const double muRef = v / tau + sign * phiOverPhi / den;
  const double s2Ref = 1.0 / tau
                       - (phiOverPhi / (tau * tau + tau)) * (z + phiOverPhi);

  double Zhat = 0.0, muHat = 0.0, s2Hat = 0.0;
  ndlnoise::bernoulliProbitEpMoments(Zhat, muHat, s2Hat, 1.0, tau, v);

  int fail = 0;
  fail += checkClose("ep_moments Zhat", Zhat, Zref);
  fail += checkClose("ep_moments muHat", muHat, muRef);
  fail += checkClose("ep_moments sigma2Hat", s2Hat, s2Ref);

  double Z0, m0, s0, Zm, mm, sm;
  ndlnoise::bernoulliProbitEpMoments(Z0, m0, s0, 0.0, tau, v);
  ndlnoise::bernoulliProbitEpMoments(Zm, mm, sm, -1.0, tau, v);
  fail += checkClose("y=0 vs y=-1 Z", Z0, Zm);
  fail += checkClose("y=0 vs y=-1 mu", m0, mm);
  fail += checkClose("y=0 vs y=-1 s2", s0, sm);
  return fail;
}

// Frozen twin of GPy EP on a 4-point 1-D RBF problem (variance=1, lengthscale=1,
// jitter=1e-6). Regenerated by cip/cip0033/gen_ep_fixture.py when GPy is available;
// values below checked against that script's numpy twin (same formulas as CEpInference).
static int testEpLogMarginalFixture()
{
  const unsigned int n = 4;
  CMatrix X(n, 1), Y(n, 1);
  const double xs[] = {-1.5, -0.5, 0.5, 1.5};
  const double ys[] = {1.0, 1.0, 0.0, 0.0};
  for(unsigned int i = 0; i < n; i++)
  {
    X.setVal(xs[i], i, 0);
    Y.setVal(ys[i], i, 0);
  }
  CRbfKern kern(X);
  kern.setVariance(1.0);
  kern.setLengthScale(1.0);
  CMatrix K(n, n);
  kern.compute(K, X);

  CEpInference ep;
  ep.setJitter(1e-6);
  ep.setTol(1e-8);
  CEpSites sites;
  CMatrix mu, varDiag;
  const double L = ep.run(K, Y, sites, mu, varDiag);

  // Frozen numpy twin: cip/cip0033/ep_ftc_fixture.txt (gen_ep_fixture.py).
  const double Lref = -2.6383083598669410e+00;
  int fail = 0;
  fail += checkClose("EP converged", ep.converged() ? 1.0 : 0.0, 1.0, 0.0);
  fail += checkClose("fixture log_marginal", L, Lref, 1e-10);
  fail += checkClose("fixture iters", (double)ep.lastIters(), 7.0, 0.0);
  return fail;
}

static int testCGpEpOptimise()
{
  const unsigned int n = 8;
  CMatrix X(n, 1), Y(n, 1);
  for(unsigned int i = 0; i < n; i++)
  {
    const double x = -1.5 + 3.0 * (double)i / (double)(n - 1);
    X.setVal(x, i, 0);
    Y.setVal(x < 0.0 ? 1.0 : 0.0, i, 0);
  }
  CRbfKern kern(X);
  kern.setVariance(1.0);
  kern.setLengthScale(0.8);
  CProbitNoise noise(&Y);
  CGp model(&kern, &noise, &X, CGp::FTC, 0, 0);
  model.setEpInference(true);
  model.setVerbosity(0);

  const double L0 = model.logLikelihood();
  CMatrix g(1, model.getOptNumParams());
  const double Lg = model.logLikelihoodGradient(g);
  int fail = 0;
  fail += checkClose("CGp EP LL finite", std::isfinite(L0) ? 1.0 : 0.0, 1.0, 0.0);
  fail += checkClose("CGp EP grad LL match", Lg, L0, 1e-12);
  for(unsigned int i = 0; i < g.getCols(); i++)
    fail += checkClose("CGp EP grad finite", std::isfinite(g.getVal(0, i)) ? 1.0 : 0.0, 1.0, 0.0);

  // FD vs analytic on first free kern param.
  CMatrix p0(1, model.getOptNumParams());
  model.getOptParams(p0);
  const double u0 = p0.getVal(0);
  const double h = 1e-5 * max(1.0, fabs(u0));
  CMatrix pp(p0), pm(p0);
  pp.setVal(u0 + h, 0);
  pm.setVal(u0 - h, 0);
  model.setOptParams(pp);
  const double Lp = model.logLikelihood();
  model.setOptParams(pm);
  const double Lm = model.logLikelihood();
  model.setOptParams(p0);
  const double fd = (Lp - Lm) / (2.0 * h);
  const double an = g.getVal(0);
  const double rel = fabs(fd - an) / max(1.0, fabs(fd));
  cout << "  CGp EP FD=" << fd << " analytic=" << an << " rel=" << rel << endl;
  fail += checkClose("CGp EP ∂L/∂θ0 vs FD", rel < 5e-2 ? 1.0 : 0.0, 1.0, 0.0);

  model.optimise(40);
  const double L1 = model.logLikelihood();
  cout << "  CGp EP optimise L0=" << L0 << " → L1=" << L1 << endl;
  fail += checkClose("CGp EP optimise improves or flat",
                     (L1 >= L0 - 1e-6) ? 1.0 : 0.0, 1.0, 0.0);
  fail += checkClose("CGp EP after opt finite", std::isfinite(L1) ? 1.0 : 0.0, 1.0, 0.0);
  return fail;
}

class CTwoBlockStandIn : public CGaussianNoise
{
 public:
  CTwoBlockStandIn(CMatrix* y) : CGaussianNoise(y) {}
  unsigned int blockSize() const { return 2; }
};

// CIP-003E: multi-output EP through CGp. With Gaussian noise EP is exact, so the
// block path must reproduce the exact CGp likelihood and kernel gradients.
static int testCGpBlockEpGaussian()
{
  const unsigned int n = 9, D = 3;
  CMatrix X(n, 1), Y(n, D);
  for(unsigned int i = 0; i < n; i++)
  {
    const double x = -1.5 + 3.0 * (double)i / (double)(n - 1);
    X.setVal(x, i, 0);
    for(unsigned int j = 0; j < D; j++)
      Y.setVal(sin((1.0 + j) * x) + 0.1 * i * (j - 1.0), i, j);
  }
  // CGp subtracts the column means (bias) and the EP path does not: centre Y
  // so the two describe the same model.
  for(unsigned int j = 0; j < D; j++)
  {
    double m = 0.0;
    for(unsigned int i = 0; i < n; i++) m += Y.getVal(i, j);
    m /= (double)n;
    for(unsigned int i = 0; i < n; i++) Y.setVal(Y.getVal(i, j) - m, i, j);
  }
  int fail = 0;
  CRbfKern kA(X), kB(X);
  kA.setVariance(1.3); kA.setLengthScale(0.9);
  kB.setVariance(1.3); kB.setLengthScale(0.9);
  CGaussianNoise nA(&Y), nB(&Y);
  nA.setSigma2(0.2); nB.setSigma2(0.2);
  CGp exact(&kA, &nA, &X, CGp::FTC, 0, 0);
  CGp ep(&kB, &nB, &X, CGp::FTC, 0, 0);
  ep.setEpInference(true);
  const double Le = exact.logLikelihood();
  const double Lp = ep.logLikelihood();
  fail += checkClose("CGp block EP (D=3 Gaussian) log likelihood == exact", Lp, Le, 1e-3);
  CMatrix gE(1, exact.getOptNumParams()), gP(1, ep.getOptNumParams());
  exact.logLikelihoodGradient(gE);
  ep.logLikelihoodGradient(gP);
  for(unsigned int i = 0; i < kA.getNumParams(); i++)
    fail += checkClose("CGp block EP kern gradient == exact", gP.getVal(i), gE.getVal(i), 1e-3);
  // Predictive latent mean/var must match the exact GP posterior.
  CMatrix Xt(2, 1); Xt.setVal(-0.3, 0, 0); Xt.setVal(0.7, 1, 0);
  CMatrix mu, vd;
  ep.epLatentMeanVar(mu, vd, Xt);
  fail += checkClose("CGp block EP predictive shape", (mu.getRows() == 2 && mu.getCols() == D) ? 1.0 : 0.0, 1.0, 0.0);
  CMatrix mE(2, D), vE(2, D);
  exact.latentMeanVar(mE, vE, Xt);
  for(unsigned int j = 0; j < D; j++)
  {
    fail += checkClose("CGp block EP predictive mean == exact", mu.getVal(0, j), mE.getVal(0, j), 1e-3);
    fail += checkClose("CGp block EP latent variance == exact", vd.getVal(1, j), vE.getVal(1, j), 1e-3);
  }

  // Refusal: a likelihood without cavity moments cannot drive multi-output EP.
  CMatrix Yb(n, 2);
  for(unsigned int i = 0; i < n; i++) { Yb.setVal(1.0, i, 0); Yb.setVal(0.5, i, 1); }
  CRbfKern kC(X);
  CStudentTNoise st(&Yb);
  CGp bad(&kC, &st, &X, CGp::FTC, 0, 0);
  bool threw = false;
  try { bad.setEpInference(true); }
  catch(ndlexceptions::Error&) { threw = true; }
  fail += checkClose("CGp EP refuses likelihood without cavity moments", threw ? 1.0 : 0.0, 1.0, 0.0);
  // Laplace refuses a coupled block whose likelihood lacks point derivatives
  // (the Gaussian stand-in; softmax is accepted, see testCGpSoftmaxLaplace).
  {
    CMatrix Y1(n, 1);
    for(unsigned int i = 0; i < n; i++) Y1.setVal(i % 2 ? 1.0 : 0.0, i, 0);
    CRbfKern kL(X);
    CTwoBlockStandIn tb(&Y1);
    CGp lap(&kL, &tb, &X, CGp::FTC, 0, 0);
    bool th = false;
    try { lap.setLaplaceInference(true); }
    catch(ndlexceptions::Error&) { th = true; }
    fail += checkClose("CGp Laplace refuses blockSize>1", th ? 1.0 : 0.0, 1.0, 0.0);
  }
  return fail;
}

// CIP-003E: Laplace for D scalar-block outputs is D independent problems on a
// shared kernel: the likelihood and kernel gradient are the column sums.
static int testCGpLaplaceMultiOutput()
{
  const unsigned int n = 10, D = 2;
  CMatrix X(n, 1), Y(n, D), Yc[2] = {CMatrix(n, 1), CMatrix(n, 1)};
  for(unsigned int i = 0; i < n; i++)
  {
    const double x = -1.5 + 3.0 * (double)i / (double)(n - 1);
    X.setVal(x, i, 0);
    for(unsigned int j = 0; j < D; j++)
    {
      const double v = (sin((1.0 + j) * x) + 0.15 * (j - 0.5) > 0.0) ? 1.0 : -1.0;
      Y.setVal(v, i, j);
      Yc[j].setVal(v, i, 0);
    }
  }
  int fail = 0;
  CRbfKern kJ(X), k0(X), k1(X);
  CProbitNoise nJ(&Y), n0(&Yc[0]), n1(&Yc[1]);
  CGp joint(&kJ, &nJ, &X, CGp::FTC, 0, 0);
  CGp g0(&k0, &n0, &X, CGp::FTC, 0, 0), g1(&k1, &n1, &X, CGp::FTC, 0, 0);
  joint.setLaplaceInference(true); g0.setLaplaceInference(true); g1.setLaplaceInference(true);
  fail += checkClose("CGp Laplace D=2 log likelihood == sum of columns",
                     joint.logLikelihood(), g0.logLikelihood() + g1.logLikelihood(), 1e-10);
  CMatrix gj(1, joint.getOptNumParams()), a(1, g0.getOptNumParams()), b(1, g1.getOptNumParams());
  joint.logLikelihoodGradient(gj); g0.logLikelihoodGradient(a); g1.logLikelihoodGradient(b);
  for(unsigned int i = 0; i < kJ.getNumParams(); i++)
    fail += checkClose("CGp Laplace D=2 kern gradient == sum of columns",
                       gj.getVal(i), a.getVal(i) + b.getVal(i), 1e-9);
  CMatrix Xt(2, 1); Xt.setVal(-0.4, 0, 0); Xt.setVal(0.9, 1, 0);
  CMatrix mj, vj, m0, v0;
  joint.laplaceLatentMeanVar(mj, vj, Xt);
  g1.laplaceLatentMeanVar(m0, v0, Xt);
  fail += checkClose("CGp Laplace D=2 predictive column 1 == single",
                     mj.getVal(1, 1), m0.getVal(1, 0), 1e-10);
  fail += checkClose("CGp Laplace D=2 predictive var column 1 == single",
                     vj.getVal(0, 1), v0.getVal(0, 0), 1e-10);
  return fail;
}

static int testLaplaceDerivsAndMode()
{
  // W = r(t+r) at f=0.5, y=1: t=0.5
  double logp = 0.0, d1 = 0.0, W = 0.0, dW = 0.0;
  ndlnoise::bernoulliProbitLaplaceDerivs(logp, d1, W, dW, 1.0, 0.5);
  const double t = 0.5;
  const double r = ndlutil::gradLnCumGaussian(t);
  int fail = 0;
  fail += checkClose("Laplace logp", logp, ndlutil::lnCumGaussian(t));
  fail += checkClose("Laplace d1", d1, r);
  fail += checkClose("Laplace W", W, r * (t + r));

  // FD on W vs dW
  const double h = 1e-6;
  double lp2, d12, Wp, dWp, Wm, dWm;
  ndlnoise::bernoulliProbitLaplaceDerivs(lp2, d12, Wp, dWp, 1.0, 0.5 + h);
  ndlnoise::bernoulliProbitLaplaceDerivs(lp2, d12, Wm, dWm, 1.0, 0.5 - h);
  const double fdW = (Wp - Wm) / (2.0 * h);
  fail += checkClose("Laplace dW/df vs FD", dW, fdW, 1e-6);

  const unsigned int n = 4;
  CMatrix X(n, 1), Y(n, 1);
  const double xs[] = {-1.5, -0.5, 0.5, 1.5};
  const double ys[] = {1.0, 1.0, 0.0, 0.0};
  for(unsigned int i = 0; i < n; i++)
  {
    X.setVal(xs[i], i, 0);
    Y.setVal(ys[i], i, 0);
  }
  CRbfKern kern(X);
  kern.setVariance(1.0);
  kern.setLengthScale(1.0);
  CMatrix K(n, n);
  kern.compute(K, X);

  CLaplaceInference lap;
  lap.setJitter(1e-6);
  lap.setTol(1e-6);
  const double L = lap.run(K, Y);
  // Frozen numpy twin: cip/cip0033/laplace_ftc_fixture.txt
  const double Lref = -2.6616263191143181e+00;
  fail += checkClose("Laplace converged", lap.converged() ? 1.0 : 0.0, 1.0, 0.0);
  fail += checkClose("Laplace fixture log_marginal", L, Lref, 1e-10);
  fail += checkClose("Laplace fixture iters", (double)lap.lastIters(), 3.0, 0.0);

  // Same toy under EP: approximations should be in the same ballpark.
  CEpInference ep;
  ep.setJitter(1e-6);
  ep.setTol(1e-8);
  CEpSites sites;
  CMatrix mu, vd;
  const double Lep = ep.run(K, Y, sites, mu, vd);
  fail += checkClose("Laplace vs EP |ΔL|<1", fabs(L - Lep) < 1.0 ? 1.0 : 0.0, 1.0, 0.0);
  cout << "  EP L=" << Lep << " |L_lap-L_ep|=" << fabs(L - Lep) << endl;
  return fail;
}

